    // ========== 链表操作：addLast0 ==========
    private void addLast0(AbstractChannelHandlerContext newCtx) {
        // 获取 tail 的前一个节点（即原来的最后一个节点）
        AbstractChannelHandlerContext prev = tail.prev;
        // 新节点的前驱指向原来的最后一个节点
        newCtx.prev = prev;
        // 新节点的后继指向 tail
        newCtx.next = tail;
        // 原来最后一个节点的后继指向新节点
        prev.next = newCtx;
        // tail 的前驱指向新节点
        tail.prev = newCtx;
    }

