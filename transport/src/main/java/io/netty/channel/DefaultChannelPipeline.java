    // ========== 链表操作：addAfter0 ==========
    private static void addAfter0(AbstractChannelHandlerContext ctx, AbstractChannelHandlerContext newCtx) {
        // 新节点的前驱指向目标节点
        newCtx.prev = ctx;
        // 新节点的后继指向目标节点的后继
        newCtx.next = ctx.next;
        // 目标节点的后继的前驱指向新节点
        ctx.next.prev = newCtx;
        // 目标节点的后继指向新节点
        ctx.next = newCtx;
    }

